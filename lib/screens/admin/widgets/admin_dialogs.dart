import 'package:file_picker/file_picker.dart';
import 'package:flutter/material.dart';
import '../../../services/shop_service.dart';
import '../../../services/shop_settings_service.dart';
import '../../../services/admin_staff_service.dart';
import 'branch_dialog/branch_dialog_header.dart';
import 'branch_dialog/branch_dialog_footer.dart';
import 'branch_dialog/branch_save_helper.dart';
import 'branch_dialog/step_01_basic_info_section.dart';
import 'branch_dialog/step_02_address_contact_section.dart';
import 'branch_dialog/step_03_operating_settings_section.dart';
import 'branch_dialog/step_04_billing_tax_section.dart';
import 'branch_dialog/step_05_staff_permissions_section.dart';

export 'add_staff_user_dialog.dart';

class AddBranchDialog extends StatefulWidget {
  final Shop? existingBranch;
  final VoidCallback onSaved;

  const AddBranchDialog({
    super.key,
    this.existingBranch,
    required this.onSaved,
  });

  @override
  State<AddBranchDialog> createState() => _AddBranchDialogState();
}

class _AddBranchDialogState extends State<AddBranchDialog> with SingleTickerProviderStateMixin {
  late TabController _tabController;
  int _currentStep = 0;
  bool _isSubmitting = false;

  // SECTION 01: BASIC INFORMATION
  late final TextEditingController _nameCtrl;
  late final TextEditingController _codeCtrl;
  String _outletType = 'Dine-in, Takeaway & Delivery';
  String _status = 'Active';
  final _descriptionCtrl = TextEditingController();
  final _tenantId = 'AUTOGENERATED-TENANT';
  String? _logoUrl;
  bool _isUploadingLogo = false;

  // SECTION 02: ADDRESS & CONTACT
  final _addressLine1Ctrl = TextEditingController();
  final _addressLine2Ctrl = TextEditingController();
  final _cityCtrl = TextEditingController(text: 'Kolkata');
  final _stateCtrl = TextEditingController(text: 'West Bengal');
  final _pinCodeCtrl = TextEditingController();
  final _countryCtrl = TextEditingController(text: 'India');
  final _phoneCtrl = TextEditingController();
  final _emailCtrl = TextEditingController();
  final _latLngCtrl = TextEditingController();

  // SECTION 03: OPERATING SETTINGS
  String _timeZone = 'Asia/Kolkata (IST +5:30)';
  String _currency = 'INR (₹)';
  final _openingTimeCtrl = TextEditingController(text: '09:00 AM');
  final _closingTimeCtrl = TextEditingController(text: '11:00 PM');
  String _weeklyClosing = 'None (Open 7 Days)';
  bool _enableDineIn = true, _enableTakeaway = true, _enableDelivery = true, _isPrimary = false;

  // SECTION 04: BILLING & TAX
  String _gstStatus = 'Registered (Regular)';
  final _gstinCtrl = TextEditingController();
  final _invoicePrefixCtrl = TextEditingController(text: 'SB');
  final _billNumberFormatCtrl = TextEditingController(text: '{PREFIX}-{YYYY}-{0001}');
  final _taxRateCtrl = TextEditingController(text: '5.0');
  String _rounding = 'Round to Nearest Rupee';
  final _receiptFooterCtrl = TextEditingController(text: 'Thank you for dining with us! Visit again.');
  final _fssaiCtrl = TextEditingController();
  final _upiIdCtrl = TextEditingController();
  final _bankAccountNameCtrl = TextEditingController(), _bankNameCtrl = TextEditingController();
  final _bankAccountCtrl = TextEditingController(), _bankIfscCtrl = TextEditingController(), _bankBranchCtrl = TextEditingController();

  // SECTION 05: STAFF & PERMISSIONS
  String? _assignedManager;
  final List<String> _assignedStaff = [];
  bool _allowMultiOutletAccess = true;
  final _maxDiscountLimitCtrl = TextEditingController(text: '20');
  final _maxRefundLimitCtrl = TextEditingController(text: '2000');

  List<RestaurantStaffUser> _availableStaff = [];
  bool _loadingStaff = true;

  @override
  void initState() {
    super.initState();
    final b = widget.existingBranch;
    _nameCtrl = TextEditingController(text: b?.name ?? '');
    _codeCtrl = TextEditingController(text: b?.code ?? '');
    if (b != null) {
      final raw = b.rawJson ?? {};
      final extra = (raw['extra_data'] is Map<String, dynamic>)
          ? raw['extra_data'] as Map<String, dynamic>
          : <String, dynamic>{};

      _status = b.status.isNotEmpty ? b.status : (extra['status'] ?? raw['status'] ?? 'Active');
      _isPrimary = b.isPrimary;
      _outletType = b.outletType ?? extra['outlet_type'] ?? raw['outlet_type'] ?? _outletType;
      _logoUrl = b.logoUrl ?? raw['logo_url'] ?? extra['logo_url'];
      _timeZone = b.timeZone ?? extra['time_zone'] ?? raw['time_zone'] ?? _timeZone;
      _currency = b.currency ?? extra['currency'] ?? raw['currency'] ?? _currency;
      _weeklyClosing = extra['weekly_closing'] ?? raw['weekly_closing'] ?? _weeklyClosing;
      _enableDineIn = extra['enable_dine_in'] ?? raw['enable_dine_in'] ?? _enableDineIn;
      _enableTakeaway = extra['enable_takeaway'] ?? raw['enable_takeaway'] ?? _enableTakeaway;
      _enableDelivery = extra['enable_delivery'] ?? raw['enable_delivery'] ?? _enableDelivery;
      _gstStatus = extra['gst_status'] ?? raw['gst_status'] ?? _gstStatus;
      _rounding = extra['rounding'] ?? raw['rounding'] ?? _rounding;
      _assignedManager = extra['manager_id'] ?? raw['manager_id'];
      _allowMultiOutletAccess = extra['allow_multi_outlet'] ?? raw['allow_multi_outlet'] ?? _allowMultiOutletAccess;

      BranchFormInitializer.populate(
        b: b,
        descriptionCtrl: _descriptionCtrl,
        addressLine1Ctrl: _addressLine1Ctrl,
        addressLine2Ctrl: _addressLine2Ctrl,
        cityCtrl: _cityCtrl,
        stateCtrl: _stateCtrl,
        pinCodeCtrl: _pinCodeCtrl,
        countryCtrl: _countryCtrl,
        phoneCtrl: _phoneCtrl,
        emailCtrl: _emailCtrl,
        latLngCtrl: _latLngCtrl,
        openingTimeCtrl: _openingTimeCtrl,
        closingTimeCtrl: _closingTimeCtrl,
        gstinCtrl: _gstinCtrl,
        invoicePrefixCtrl: _invoicePrefixCtrl,
        billNumberFormatCtrl: _billNumberFormatCtrl,
        taxRateCtrl: _taxRateCtrl,
        receiptFooterCtrl: _receiptFooterCtrl,
        fssaiCtrl: _fssaiCtrl,
        upiIdCtrl: _upiIdCtrl,
        bankAccountNameCtrl: _bankAccountNameCtrl,
        bankNameCtrl: _bankNameCtrl,
        bankAccountCtrl: _bankAccountCtrl,
        bankIfscCtrl: _bankIfscCtrl,
        bankBranchCtrl: _bankBranchCtrl,
        maxDiscountLimitCtrl: _maxDiscountLimitCtrl,
        maxRefundLimitCtrl: _maxRefundLimitCtrl,
        assignedStaff: _assignedStaff,
      );
    }

    _tabController = TabController(length: 5, vsync: this);
    _tabController.addListener(() {
      if (_tabController.indexIsChanging || _tabController.index != _currentStep) {
        setState(() => _currentStep = _tabController.index);
      }
    });
    _fetchStaffMembers();
  }

  Future<void> _pickAndUploadLogo() async {
    try {
      final result = await FilePicker.platform.pickFiles(
        type: FileType.custom,
        allowedExtensions: ['jpg', 'jpeg', 'png', 'webp'],
        withData: true,
      );

      if (result == null || result.files.isEmpty) return;

      final file = result.files.first;
      final fileBytes = file.bytes;

      if (fileBytes == null) {
        _showWarning('Unable to read selected logo file bytes.');
        return;
      }

      setState(() => _isUploadingLogo = true);

      final uploadedUrl = await ShopSettingsService.uploadLogo(fileBytes, file.name);

      if (mounted) {
        setState(() {
          _logoUrl = uploadedUrl;
          _isUploadingLogo = false;
        });
        ScaffoldMessenger.of(context).showSnackBar(
          const SnackBar(
            content: Text('Branch logo uploaded successfully! Remember to save profile.'),
            backgroundColor: Color(0xFF10B981),
            behavior: SnackBarBehavior.floating,
          ),
        );
      }
    } catch (e) {
      if (mounted) {
        setState(() => _isUploadingLogo = false);
        _showWarning('Failed to upload logo: $e');
      }
    }
  }

  Future<void> _fetchStaffMembers() async {
    try {
      final staff = await AdminStaffService.getStaffUsers();
      if (mounted) {
        setState(() {
          _availableStaff = staff;
          _loadingStaff = false;
        });
      }
    } catch (_) {
      if (mounted) setState(() => _loadingStaff = false);
    }
  }

  @override
  void dispose() {
    _tabController.dispose();
    for (final c in [
      _nameCtrl, _codeCtrl, _descriptionCtrl, _addressLine1Ctrl, _addressLine2Ctrl,
      _cityCtrl, _stateCtrl, _pinCodeCtrl, _countryCtrl, _phoneCtrl, _emailCtrl,
      _latLngCtrl, _openingTimeCtrl, _closingTimeCtrl, _gstinCtrl, _invoicePrefixCtrl,
      _billNumberFormatCtrl, _taxRateCtrl, _receiptFooterCtrl, _fssaiCtrl, _upiIdCtrl,
      _bankAccountNameCtrl, _bankNameCtrl, _bankAccountCtrl, _bankIfscCtrl,
      _bankBranchCtrl, _maxDiscountLimitCtrl, _maxRefundLimitCtrl,
    ]) {
      c.dispose();
    }
    super.dispose();
  }

  Future<void> _saveOutlet() async {
    final rawPhone = _phoneCtrl.text.trim().replaceAll(RegExp(r'\D'), '');
    final validation = BranchSaveHelper.validate(
      name: _nameCtrl.text.trim(),
      addressLine1: _addressLine1Ctrl.text.trim(),
      city: _cityCtrl.text.trim(),
      rawPhone: rawPhone,
      gstStatus: _gstStatus,
      gstin: _gstinCtrl.text.trim().toUpperCase(),
      fssai: _fssaiCtrl.text.trim(),
    );

    if (!validation.isValid) {
      _showWarning(validation.errorMessage!);
      if (validation.targetTabIndex != null) {
        _tabController.animateTo(validation.targetTabIndex!);
      }
      return;
    }

    final formattedPhone = '+91 $rawPhone';
    setState(() => _isSubmitting = true);
    try {
      final formattedAddress = [
        _addressLine1Ctrl.text.trim(),
        if (_addressLine2Ctrl.text.trim().isNotEmpty) _addressLine2Ctrl.text.trim(),
        if (_stateCtrl.text.trim().isNotEmpty) _stateCtrl.text.trim(),
        if (_pinCodeCtrl.text.trim().isNotEmpty) 'PIN: ${_pinCodeCtrl.text.trim()}',
      ].join(', ');

      final extraData = BranchSaveHelper.buildExtraData(
        outletType: _outletType,
        description: _descriptionCtrl.text.trim(),
        addressLine1: _addressLine1Ctrl.text.trim(),
        addressLine2: _addressLine2Ctrl.text.trim(),
        state: _stateCtrl.text.trim(),
        pinCode: _pinCodeCtrl.text.trim(),
        country: _countryCtrl.text.trim(),
        email: _emailCtrl.text.trim(),
        latLng: _latLngCtrl.text.trim(),
        timeZone: _timeZone,
        currency: _currency,
        openingTime: _openingTimeCtrl.text.trim(),
        closingTime: _closingTimeCtrl.text.trim(),
        weeklyClosing: _weeklyClosing,
        enableDineIn: _enableDineIn,
        enableTakeaway: _enableTakeaway,
        enableDelivery: _enableDelivery,
        gstStatus: _gstStatus,
        gstin: _gstinCtrl.text.trim(),
        invoicePrefix: _invoicePrefixCtrl.text.trim(),
        billNumberFormat: _billNumberFormatCtrl.text.trim(),
        taxRate: double.tryParse(_taxRateCtrl.text.trim()) ?? 5.0,
        rounding: _rounding,
        receiptFooter: _receiptFooterCtrl.text.trim(),
        fssai: _fssaiCtrl.text.trim(),
        upiId: _upiIdCtrl.text.trim(),
        bankAccountName: _bankAccountNameCtrl.text.trim(),
        bankName: _bankNameCtrl.text.trim(),
        bankAccount: _bankAccountCtrl.text.trim(),
        bankIfsc: _bankIfscCtrl.text.trim().toUpperCase(),
        bankBranch: _bankBranchCtrl.text.trim(),
        managerId: _assignedManager,
        assignedStaff: _assignedStaff,
        allowMultiOutlet: _allowMultiOutletAccess,
        maxDiscountLimit: double.tryParse(_maxDiscountLimitCtrl.text.trim()) ?? 20.0,
        maxRefundLimit: double.tryParse(_maxRefundLimitCtrl.text.trim()) ?? 2000.0,
        logoUrl: _logoUrl,
      );

      await BranchSaveHelper.saveBranch(
        existingBranch: widget.existingBranch,
        name: _nameCtrl.text.trim(),
        code: _codeCtrl.text.trim(),
        formattedAddress: formattedAddress,
        city: _cityCtrl.text.trim(),
        formattedPhone: formattedPhone,
        status: _status,
        isPrimary: _isPrimary,
        extraData: extraData,
      );

      if (mounted) {
        Navigator.pop(context);
        widget.onSaved();
      }
    } catch (e) {
      if (mounted) {
        setState(() => _isSubmitting = false);
        _showWarning(e.toString());
      }
    }
  }

  void _showWarning(String msg) {
    ScaffoldMessenger.of(context).showSnackBar(
      SnackBar(
        content: Text(msg),
        backgroundColor: const Color(0xFFEF4444),
        behavior: SnackBarBehavior.floating,
      ),
    );
  }

  @override
  Widget build(BuildContext context) {
    final isDark = Theme.of(context).brightness == Brightness.dark;
    final dialogBg = isDark ? const Color(0xFF0F172A) : Colors.white;
    final cardBg = isDark ? const Color(0xFF1E293B) : const Color(0xFFF8FAFC);
    final borderColor = isDark ? const Color(0xFF334155) : const Color(0xFFE2E8F0);
    final textColor = isDark ? Colors.white : const Color(0xFF0F172A);
    final subtitleColor = isDark ? const Color(0xFF94A3B8) : const Color(0xFF64748B);

    const tabs = BranchDialogHeader.defaultTabs;

    final screenWidth = MediaQuery.of(context).size.width;
    final isMobile = screenWidth < 650;
    final dialogWidth = screenWidth > 900 ? 840.0 : (isMobile ? double.infinity : screenWidth * 0.95);

    return Dialog(
      backgroundColor: dialogBg,
      shape: RoundedRectangleBorder(borderRadius: BorderRadius.circular(18)),
      insetPadding: EdgeInsets.symmetric(
        horizontal: isMobile ? 12 : 16,
        vertical: isMobile ? 16 : 24,
      ),
      child: Container(
        width: dialogWidth,
        height: isMobile ? MediaQuery.of(context).size.height * 0.88 : 680,
        decoration: BoxDecoration(
          color: dialogBg,
          borderRadius: BorderRadius.circular(18),
        ),
        child: Column(
          children: [
            BranchDialogHeader(
              isDark: isDark,
              borderColor: borderColor,
              textColor: textColor,
              subtitleColor: subtitleColor,
              isEdit: widget.existingBranch != null,
              tabController: _tabController,
              tabs: tabs,
              onClose: () => Navigator.pop(context),
            ),

            // TAB CONTENT BODY (Delegated to modularized sub-widgets)
            Expanded(
              child: TabBarView(
                controller: _tabController,
                children: [
                  Step01BasicInfoSection(
                    nameCtrl: _nameCtrl,
                    codeCtrl: _codeCtrl,
                    outletType: _outletType,
                    onOutletTypeChanged: (val) => setState(() => _outletType = val ?? _outletType),
                    status: _status,
                    onStatusChanged: (val) => setState(() => _status = val ?? _status),
                    tenantId: _tenantId,
                    descriptionCtrl: _descriptionCtrl,
                    textColor: textColor,
                    logoUrl: _logoUrl,
                    onPickLogo: _pickAndUploadLogo,
                    onClearLogo: () => setState(() => _logoUrl = null),
                    isUploadingLogo: _isUploadingLogo,
                  ),
                  Step02AddressContactSection(
                    addressLine1Ctrl: _addressLine1Ctrl,
                    addressLine2Ctrl: _addressLine2Ctrl,
                    cityCtrl: _cityCtrl,
                    stateCtrl: _stateCtrl,
                    pinCodeCtrl: _pinCodeCtrl,
                    countryCtrl: _countryCtrl,
                    phoneCtrl: _phoneCtrl,
                    emailCtrl: _emailCtrl,
                    latLngCtrl: _latLngCtrl,
                    textColor: textColor,
                  ),
                  Step03OperatingSettingsSection(
                    timeZone: _timeZone,
                    onTimeZoneChanged: (val) => setState(() => _timeZone = val ?? _timeZone),
                    currency: _currency,
                    onCurrencyChanged: (val) => setState(() => _currency = val ?? _currency),
                    openingTimeCtrl: _openingTimeCtrl,
                    closingTimeCtrl: _closingTimeCtrl,
                    weeklyClosing: _weeklyClosing,
                    onWeeklyClosingChanged: (val) => setState(() => _weeklyClosing = val ?? _weeklyClosing),
                    enableDineIn: _enableDineIn,
                    onEnableDineInChanged: (val) => setState(() => _enableDineIn = val),
                    enableTakeaway: _enableTakeaway,
                    onEnableTakeawayChanged: (val) => setState(() => _enableTakeaway = val),
                    enableDelivery: _enableDelivery,
                    onEnableDeliveryChanged: (val) => setState(() => _enableDelivery = val),
                    isPrimary: _isPrimary,
                    onIsPrimaryChanged: (val) => setState(() => _isPrimary = val ?? false),
                    textColor: textColor,
                    subtitleColor: subtitleColor,
                  ),
                  Step04BillingTaxSection(
                    gstStatus: _gstStatus,
                    onGstStatusChanged: (val) => setState(() => _gstStatus = val ?? _gstStatus),
                    gstinCtrl: _gstinCtrl,
                    invoicePrefixCtrl: _invoicePrefixCtrl,
                    billNumberFormatCtrl: _billNumberFormatCtrl,
                    taxRateCtrl: _taxRateCtrl,
                    rounding: _rounding,
                    onRoundingChanged: (val) => setState(() => _rounding = val ?? _rounding),
                    fssaiCtrl: _fssaiCtrl,
                    receiptFooterCtrl: _receiptFooterCtrl,
                    upiIdCtrl: _upiIdCtrl,
                    bankAccountNameCtrl: _bankAccountNameCtrl,
                    bankNameCtrl: _bankNameCtrl,
                    bankAccountCtrl: _bankAccountCtrl,
                    bankIfscCtrl: _bankIfscCtrl,
                    bankBranchCtrl: _bankBranchCtrl,
                    textColor: textColor,
                  ),
                  Step05StaffPermissionsSection(
                    loadingStaff: _loadingStaff,
                    assignedManager: _assignedManager,
                    onAssignedManagerChanged: (val) => setState(() => _assignedManager = val),
                    availableStaff: _availableStaff,
                    assignedStaff: _assignedStaff,
                    onToggleStaff: (id) {
                      setState(() {
                        if (_assignedStaff.contains(id)) {
                          _assignedStaff.remove(id);
                        } else {
                          _assignedStaff.add(id);
                        }
                      });
                    },
                    maxDiscountLimitCtrl: _maxDiscountLimitCtrl,
                    maxRefundLimitCtrl: _maxRefundLimitCtrl,
                    allowMultiOutletAccess: _allowMultiOutletAccess,
                    onAllowMultiOutletAccessChanged: (val) => setState(() => _allowMultiOutletAccess = val),
                    cardBg: cardBg,
                    borderColor: borderColor,
                    textColor: textColor,
                    subtitleColor: subtitleColor,
                  ),
                ],
              ),
            ),

            BranchDialogFooter(
              isMobile: isMobile,
              currentStep: _currentStep,
              tabs: tabs,
              textColor: textColor,
              borderColor: borderColor,
              subtitleColor: subtitleColor,
              isSubmitting: _isSubmitting,
              isEdit: widget.existingBranch != null,
              onBack: () => _tabController.animateTo(_currentStep - 1),
              onContinue: () => _tabController.animateTo(_currentStep + 1),
              onSave: _saveOutlet,
            ),
          ],
        ),
      ),
    );
  }
}

